#!/usr/bin/env python3
"""Bundle the controller into an HTML file that can be opened directly."""
from pathlib import Path


def main():
    source = Path(__file__).resolve().parent
    html = (source / 'page.template.html').read_text()
    css = (source / 'style.css').read_text()
    transport = (source / 'serial.mjs').read_text().replace('export class SerialTransport', 'class SerialTransport', 1)
    transport += '\n' + (source / 'http.mjs').read_text().replace('export class HttpTransport', 'class HttpTransport', 1)
    forms = (source / 'channel-forms.js').read_text()
    app = (source / 'app.mjs').read_text().replace("import {SerialTransport} from './serial.mjs';", '', 1).replace("import {HttpTransport} from './http.mjs';", '', 1)
    javascript = "(() => {\n'use strict';\n" + transport + '\n' + forms + '\n' + app + '\n})();'
    assert '</script' not in javascript.lower()
    html = html.replace('<link rel="stylesheet" href="style.css">', '<style>\n' + css + '\n</style>')
    html = html.replace('<script src="channel-forms.js"></script><script type="module" src="app.mjs"></script>',
                        '<script>\n' + javascript + '\n</script>')
    html = html.replace('Open this page in desktop Chrome or Edge through localhost or HTTPS.',
                        'Open this HTML file in desktop Chrome or Edge. If USB access is blocked by your browser, serve the page through localhost or HTTPS.')
    assert ')HTML\"' not in html
    device_html = html.replace('<head>', '<head><script>window.FG_DEVICE_PAGE=true;</script>', 1)
    (source.parent / 'web_page.h').write_text('// Generated by web/build_standalone.py; edit web sources instead.\n#pragma once\nconst char PAGE[] PROGMEM = R\"HTML(' + device_html + ')HTML\";\n')
    for destination in (source.parent / 'function-generator.html', source / 'index.html'):
        destination.write_text(html)
        print(f'Built {destination.name}: {len(html.encode())} bytes')


if __name__ == '__main__':
    main()
